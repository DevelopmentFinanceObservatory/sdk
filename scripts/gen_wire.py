#!/usr/bin/env python3
"""Generate the Python client's wire types and strict checks from `contract/`.

    uv run --directory python ../scripts/gen_wire.py           write both modules
    uv run --directory python ../scripts/gen_wire.py --check   exit 1 on any drift

`python/src/dfo/_generated/wire.py` holds a `TypedDict` per component schema of
`contract/served/openapi.json`, generated by datamodel-code-generator. It holds types
only, since the client reads plain `json.loads` dicts without validating through them.

`python/src/dfo/_generated/strict.py` is generated from
`contract/strict-fields.json`: the members each schema must carry, with the JSON
type the served document gives each, which `dfo._core.parse.require` checks, and the
enum values the client branches on. It holds literals only and imports nothing
from `dfo`. Each pointer must name a property of a component schema; a
`required` pointer must sit in its schema's `required` list, admit no null and have
a string, array or object type, directly or through its `$ref`, and an `enums`
pointer's values must all be in the property's enum. The generator refuses a
contract that breaks any of these rules.

Run it with the package's environment, which provides datamodel-code-generator and
ruff. Both modules come out formatted with the package's ruff settings.
"""

import argparse
import json
import subprocess
import sys
import tempfile
from collections.abc import Iterator, Mapping
from pathlib import Path
from typing import Any

import sync_contract

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "python"
OPENAPI = ROOT / "contract" / "served" / "openapi.json"
STRICT_FIELDS = ROOT / "contract" / "strict-fields.json"
WIRE = PACKAGE / "src" / "dfo" / "_generated" / "wire.py"
STRICT = PACKAGE / "src" / "dfo" / "_generated" / "strict.py"
POINTER_PREFIX = "/components/schemas/"
# The JSON types a required member can be checked for.
JSON_TYPES = frozenset({"string", "array", "object"})

CODEGEN_ARGS = (
    "--input-file-type=openapi",
    "--output-model-type=typing.TypedDict",
    "--no-use-closed-typed-dict",
    "--strict-nullable",
    "--enum-field-as-literal=all",
    "--target-python-version=3.12",
    "--disable-timestamp",
    "--formatters=builtin",
)

WIRE_DOCSTRING = '''"""Wire types for every component schema of the served OpenAPI document.

Generated by `scripts/gen_wire.py` from `contract/served/openapi.json`; do not edit.
These are types only: the parser reads plain dicts, so an unknown member or enum
value passes through untouched.
"""
'''

STRICT_TEMPLATE = '''"""The response members the client acts on, from `contract/strict-fields.json`.

Generated by `scripts/gen_wire.py`; do not edit. `dfo._core.parse.require` raises
`ContractError` with code `contract_violation` when a member listed here is missing,
null or of another JSON type than the one listed. The enum constants are the values
the client branches on; any other value passes through as an unknown one.
"""

from collections.abc import Mapping
from typing import Final, Literal

type StrictSchema = Literal[{schema_names}]
type JsonType = Literal["string", "array", "object"]

# Each schema's required members, with the JSON type each must have.
REQUIRED: Final[Mapping[StrictSchema, tuple[tuple[str, JsonType], ...]]] = {{
{required}
}}

{enums}
'''


def schema_member(pointer: str) -> tuple[str, str]:
    """Split `/components/schemas/<Schema>/properties/<member>` into its names."""
    rest = pointer.removeprefix(POINTER_PREFIX)
    schema, separator, member = rest.partition("/properties/")
    if rest == pointer or not separator or not schema or not member or "/" in member:
        raise SystemExit(f"{pointer}: not a component schema property pointer")
    return schema, member


def admits_null(prop: Mapping[str, Any]) -> bool:
    """Whether an OpenAPI property admits a JSON null."""
    if prop.get("type") == "null" or prop.get("nullable") is True:
        return True
    return any(admits_null(option) for option in prop.get("anyOf", ()))


def enum_values(prop: Mapping[str, Any]) -> set[Any]:
    """The values an OpenAPI property's enum or const allows."""
    if "const" in prop:
        return {prop["const"]}
    values = set(prop.get("enum", ()))
    for option in prop.get("anyOf", ()):
        values |= enum_values(option)
    return values


def json_type(prop: Mapping[str, Any], schemas: Mapping[str, Any]) -> str | None:
    """The JSON type a required property must have, through its `$ref`, or None
    when it has no string, array or object type."""
    if ref := prop.get("$ref"):
        prop = schemas.get(ref.removeprefix("#" + POINTER_PREFIX), {})
    kind = prop.get("type")
    return kind if kind in JSON_TYPES else None


def strict_fields(
    schemas: Mapping[str, Any], fields: Mapping[str, Any]
) -> tuple[dict[str, list[tuple[str, str]]], dict[tuple[str, str], list[str]]]:
    """Check the strict pointers against the served schemas and group them.

    Returns:
        The required members and their JSON types by schema, and the enum values
        by schema and member, each in contract order.
    """
    required: dict[str, list[tuple[str, str]]] = {}
    for entry in fields["required"]:
        schema, member = schema_member(entry["pointer"])
        prop = schemas.get(schema, {}).get("properties", {}).get(member)
        if prop is None:
            raise SystemExit(f"{entry['pointer']}: not in the served document")
        if member not in schemas[schema].get("required", ()):
            raise SystemExit(f"{entry['pointer']}: not required by {schema}")
        if admits_null(prop):
            raise SystemExit(f"{entry['pointer']}: admits null in {schema}")
        kind = json_type(prop, schemas)
        if kind is None:
            raise SystemExit(
                f"{entry['pointer']}: has no string, array or object type in {schema}"
            )
        required.setdefault(schema, []).append((member, kind))

    enums: dict[tuple[str, str], list[str]] = {}
    for entry in fields["enums"]:
        schema, member = schema_member(entry["pointer"])
        prop = schemas.get(schema, {}).get("properties", {}).get(member)
        if prop is None:
            raise SystemExit(f"{entry['pointer']}: not in the served document")
        unknown = set(entry["values"]) - enum_values(prop)
        if unknown:
            raise SystemExit(f"{entry['pointer']}: {sorted(unknown)} not served")
        enums[schema, member] = list(entry["values"])
    if not required or not enums:
        raise SystemExit(f"{STRICT_FIELDS}: no required or no enum pointers")
    return required, enums


def constant_name(schema: str, member: str) -> str:
    """`DefinitePart`, `status` -> `DEFINITE_PART_STATUS`."""
    words = "".join(f"_{c}" if c.isupper() else c for c in schema).lstrip("_")
    return f"{words}_{member}".upper()


def enum_lines(enums: Mapping[tuple[str, str], list[str]]) -> Iterator[str]:
    """One constant per enum pointer, a string for one value and a tuple for several."""
    for (schema, member), values in enums.items():
        name = constant_name(schema, member)
        if len(values) == 1:
            yield f"{name}: Final = {json.dumps(values[0])}"
        else:
            yield f"{name}: Final = {tuple(values)!r}"


def render_strict(document: Mapping[str, Any], fields: Mapping[str, Any]) -> str:
    """The source of `_generated/strict.py`, before formatting."""
    required, enums = strict_fields(document["components"]["schemas"], fields)
    return STRICT_TEMPLATE.format(
        schema_names=", ".join(json.dumps(name) for name in required),
        required="\n".join(
            f"    {json.dumps(schema)}: {tuple(members)!r},"
            for schema, members in required.items()
        ),
        enums="\n".join(enum_lines(enums)),
    )


def render_wire() -> str:
    """The source of `_generated/wire.py`, before formatting."""
    with tempfile.TemporaryDirectory() as scratch:
        output = Path(scratch) / "wire.py"
        # Its warnings about `$id`-relative references repeat on every run, so its
        # output is shown only when it fails.
        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                f"--input={OPENAPI}",
                f"--output={output}",
                *CODEGEN_ARGS,
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            raise SystemExit(f"datamodel-code-generator failed:\n{result.stderr}")
        lines = output.read_text().splitlines(keepends=True)
    # datamodel-code-generator opens with a comment block naming its input. The
    # module docstring replaces it.
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    return WIRE_DOCSTRING + "".join(lines)


def ruff(source: str, target: Path, *args: str) -> str:
    """Run a ruff command over `source` as if it were `target`, returning stdout."""
    return subprocess.run(
        [sys.executable, "-m", "ruff", *args, "--stdin-filename", str(target), "-"],
        input=source,
        cwd=PACKAGE,
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def ruff_format(source: str, target: Path) -> str:
    """Fix and format `source` as ruff would `target`, under the package's settings."""
    fixed = ruff(source, target, "check", "--fix-only", "--exit-zero")
    return ruff(fixed, target, "format")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when a generated module differs instead of writing",
    )
    args = parser.parse_args()

    sync_contract.require_current()
    document = json.loads(OPENAPI.read_text())
    fields = json.loads(STRICT_FIELDS.read_text())
    generated = {
        WIRE: ruff_format(render_wire(), WIRE),
        STRICT: ruff_format(render_strict(document, fields), STRICT),
    }

    if args.check:
        stale = [
            path
            for path, source in generated.items()
            if not path.exists() or path.read_text() != source
        ]
        for path in stale:
            print(
                f"{path.relative_to(ROOT)} is stale; run scripts/gen_wire.py",
                file=sys.stderr,
            )
        return 1 if stale else 0

    for path, source in generated.items():
        path.write_text(source)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
