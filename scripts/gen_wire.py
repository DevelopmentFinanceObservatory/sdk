#!/usr/bin/env python3
"""Generate the Python client's wire types, strict checks, reading columns, role
keys and file selector keys from `contract/`.

    uv run --directory python ../scripts/gen_wire.py           write the modules
    uv run --directory python ../scripts/gen_wire.py --check   exit 1 on any drift

`python/src/dfo/_generated/wire.py` holds a `TypedDict` per component schema of
`contract/served/openapi.json`, generated by datamodel-code-generator. It holds types
only, since the client reads plain `json.loads` dicts without validating through them.

`python/src/dfo/_generated/strict.py` is generated from
`contract/strict-fields.json`: the members each schema must carry, with the JSON
type the served document gives each, which `dfo._core.parse.require` checks, and the
enum values the client branches on. It holds literals only and imports nothing
from `dfo`. Each pointer must name a property of a component schema; a
`required` pointer must sit in its schema's `required` list, admit no null and have
a string, integer, array or object type, directly or through its `$ref`, and an `enums`
pointer's values must all be in the property's enum. The generator refuses a
contract that breaks any of these rules.

`python/src/dfo/_generated/reading_order.py` holds the `reading_columns` slots of
`contract/rules/reading-order.json`, which `dfo._datasets.dataset` orders every
table by. The generator refuses a file that is not format version 1 of the
`reading-order` rule, a slot that is empty or holds other than strings, a name
listed twice, and `stat_var` or `part` in a slot.

`python/src/dfo/_generated/role_keys.py` holds the `keys` and `flow_keys` of
`contract/rules/role-keys.json`: the caller key `entities=` takes for each role,
with the wire role a build posts it as, and the flow keys. The generator refuses a
file that is not format version 1 of the `role-keys` rule, a key or wire role that
is not a name, two keys for one wire role, a wire role spelled as another role's
key, and flow keys that are empty or name a key the rule does not map to itself.

`python/src/dfo/_generated/file_selector.py` holds the `query_keys` of
`contract/rules/file-selector.json`, the only keys a version's file selector reads,
in the order a query lists them. The generator refuses a file that is not format
version 1 of the `file-selector` rule, and query keys that are empty, not names or
listed twice.

`wire.py` also declares a closed `Literal` alias for each enum in `NAMED_ENUMS`,
which the public classes read as `Name | str` and the client's options take as
`Name`. The generator refuses a path that holds no string enum and a name that
the generated module already declares.

Run it with the package's environment, which provides datamodel-code-generator and
ruff. The modules come out formatted with the package's ruff settings.
"""

import argparse
import json
import subprocess
import sys
import tempfile
from collections.abc import Iterator, Mapping
from pathlib import Path
from typing import Any

import sync_contract
from _codegen import ROOT, relative, write_or_check

PACKAGE = ROOT / "python"
OPENAPI = ROOT / "contract" / "served" / "openapi.json"
STRICT_FIELDS = ROOT / "contract" / "strict-fields.json"
WIRE = PACKAGE / "src" / "dfo" / "_generated" / "wire.py"
STRICT = PACKAGE / "src" / "dfo" / "_generated" / "strict.py"
READING_ORDER_RULE = ROOT / "contract" / "rules" / "reading-order.json"
READING_ORDER = PACKAGE / "src" / "dfo" / "_generated" / "reading_order.py"
ROLE_KEYS_RULE = ROOT / "contract" / "rules" / "role-keys.json"
ROLE_KEYS = PACKAGE / "src" / "dfo" / "_generated" / "role_keys.py"
FILE_SELECTOR_RULE = ROOT / "contract" / "rules" / "file-selector.json"
FILE_SELECTOR = PACKAGE / "src" / "dfo" / "_generated" / "file_selector.py"
POINTER_PREFIX = "/components/schemas/"
# The JSON types a required member can be checked for.
JSON_TYPES = frozenset({"string", "integer", "array", "object"})

# The enums declared as named closed aliases: each one's schema path and the line
# that documents it.
NAMED_ENUMS: dict[str, tuple[tuple[str, ...], str]] = {
    "Severity": (
        ("Warning", "properties", "severity"),
        "How much a Search warning matters.",
    ),
    "AssumptionKind": (
        ("Assumption", "properties", "kind"),
        "What Search filled in that the question left open.",
    ),
    "DepartureCode": (
        ("Departure", "properties", "code"),
        "How a reading differs from what the question asked.",
    ),
    "NoDataReason": (("NoData", "properties", "reason"), "Why a part has no data."),
    "DeclinedReason": (
        ("DeclinedAnswer", "properties", "reason"),
        "Why Search declined a question.",
    ),
    "ResolveKind": (
        (
            "graph_api__resolve_models__ResolveRequest",
            "properties",
            "kinds",
            "items",
        ),
        "A kind of graph node a name can resolve to.",
    ),
}

CODEGEN_ARGS = (
    "--input-file-type=openapi",
    "--output-model-type=typing.TypedDict",
    "--no-use-closed-typed-dict",
    "--strict-nullable",
    "--enum-field-as-literal=all",
    "--target-python-version=3.12",
    "--disable-timestamp",
    "--formatters=builtin",
)

WIRE_DOCSTRING = '''"""Wire types for every component schema of the served OpenAPI document.

Generated by `scripts/gen_wire.py` from `contract/served/openapi.json`; do not edit.
These are types only: the parser reads plain dicts, so an unknown member or enum
value passes through untouched.
"""
'''

STRICT_TEMPLATE = '''"""The response members the client acts on, from `contract/strict-fields.json`.

Generated by `scripts/gen_wire.py`; do not edit. `dfo._core.parse.require` raises
`ContractError` with code `contract_violation` when a member listed here is missing,
null or of another JSON type than the one listed. The enum constants are the values
the client branches on; any other value passes through as an unknown one.
"""

from collections.abc import Mapping
from typing import Final, Literal

type StrictSchema = Literal[{schema_names}]
type JsonType = Literal["string", "integer", "array", "object"]

# Each schema's required members, with the JSON type each must have.
REQUIRED: Final[Mapping[StrictSchema, tuple[tuple[str, JsonType], ...]]] = {{
{required}
}}

{enums}
'''

READING_ORDER_TEMPLATE = '''"""The reading columns a dataset's table leads with, from
`contract/rules/reading-order.json`.

Generated by `scripts/gen_wire.py`; do not edit. Each slot lists the names that
fill it, in order; the first name a table holds fills the slot.
"""

from typing import Final

READING_COLUMNS: Final[tuple[tuple[str, ...], ...]] = (
{slots}
)
'''

ROLE_KEYS_TEMPLATE = '''"""The caller keys a fetch's `entities` takes, from `contract/rules/role-keys.json`.

Generated by `scripts/gen_wire.py`; do not edit. A caller types the key; a build
posts the wire role it maps to.
"""

from collections.abc import Mapping
from typing import Final

# Each caller key with the wire role a build posts it as.
ROLE_KEYS: Final[Mapping[str, str]] = {{
{keys}
}}

# The flow keys: a spec that names one takes both.
FLOW_KEYS: Final[tuple[str, ...]] = {flow_keys!r}
'''

FILE_SELECTOR_TEMPLATE = '''"""The query keys a version's file selector reads, from
`contract/rules/file-selector.json`.

Generated by `scripts/gen_wire.py`; do not edit. A selector query holds the keys
a rendering holds among these, in this order.
"""

from typing import Final

SELECTOR_QUERY_KEYS: Final[tuple[str, ...]] = {query_keys!r}
'''


def schema_member(pointer: str) -> tuple[str, str]:
    """Split `/components/schemas/<Schema>/properties/<member>` into its names."""
    rest = pointer.removeprefix(POINTER_PREFIX)
    schema, separator, member = rest.partition("/properties/")
    if rest == pointer or not separator or not schema or not member or "/" in member:
        raise SystemExit(f"{pointer}: not a component schema property pointer")
    return schema, member


def admits_null(prop: Mapping[str, Any]) -> bool:
    """Whether an OpenAPI property admits a JSON null."""
    if prop.get("type") == "null" or prop.get("nullable") is True:
        return True
    return any(admits_null(option) for option in prop.get("anyOf", ()))


def enum_values(prop: Mapping[str, Any]) -> set[Any]:
    """The values an OpenAPI property's enum or const allows."""
    if "const" in prop:
        return {prop["const"]}
    values = set(prop.get("enum", ()))
    for option in prop.get("anyOf", ()):
        values |= enum_values(option)
    return values


def json_type(prop: Mapping[str, Any], schemas: Mapping[str, Any]) -> str | None:
    """The JSON type a required property must have, through its `$ref`, or None
    when it has no string, integer, array or object type."""
    if ref := prop.get("$ref"):
        prop = schemas.get(ref.removeprefix("#" + POINTER_PREFIX), {})
    kind = prop.get("type")
    return kind if kind in JSON_TYPES else None


def strict_fields(
    schemas: Mapping[str, Any], fields: Mapping[str, Any]
) -> tuple[dict[str, list[tuple[str, str]]], dict[tuple[str, str], list[str]]]:
    """Check the strict pointers against the served schemas and group them.

    Returns:
        The required members and their JSON types by schema, and the enum values
        by schema and member, each in contract order.
    """
    required: dict[str, list[tuple[str, str]]] = {}
    for entry in fields["required"]:
        schema, member = schema_member(entry["pointer"])
        prop = schemas.get(schema, {}).get("properties", {}).get(member)
        if prop is None:
            raise SystemExit(f"{entry['pointer']}: not in the served document")
        if member not in schemas[schema].get("required", ()):
            raise SystemExit(f"{entry['pointer']}: not required by {schema}")
        if admits_null(prop):
            raise SystemExit(f"{entry['pointer']}: admits null in {schema}")
        kind = json_type(prop, schemas)
        if kind is None:
            raise SystemExit(
                f"{entry['pointer']}: has no string, integer, array or object type in {schema}"
            )
        required.setdefault(schema, []).append((member, kind))

    enums: dict[tuple[str, str], list[str]] = {}
    for entry in fields["enums"]:
        schema, member = schema_member(entry["pointer"])
        prop = schemas.get(schema, {}).get("properties", {}).get(member)
        if prop is None:
            raise SystemExit(f"{entry['pointer']}: not in the served document")
        unknown = set(entry["values"]) - enum_values(prop)
        if unknown:
            raise SystemExit(f"{entry['pointer']}: {sorted(unknown)} not served")
        enums[schema, member] = list(entry["values"])
    if not required or not enums:
        raise SystemExit(f"{STRICT_FIELDS}: no required or no enum pointers")
    return required, enums


def constant_name(schema: str, member: str) -> str:
    """`DefinitePart`, `status` -> `DEFINITE_PART_STATUS`."""
    words = "".join(f"_{c}" if c.isupper() else c for c in schema).lstrip("_")
    return f"{words}_{member}".upper()


def enum_lines(enums: Mapping[tuple[str, str], list[str]]) -> Iterator[str]:
    """One constant per enum pointer, a string for one value and a tuple for several."""
    for (schema, member), values in enums.items():
        name = constant_name(schema, member)
        if len(values) == 1:
            yield f"{name}: Final = {json.dumps(values[0])}"
        else:
            yield f"{name}: Final = {tuple(values)!r}"


def render_strict(document: Mapping[str, Any], fields: Mapping[str, Any]) -> str:
    """The source of `_generated/strict.py`, before formatting."""
    required, enums = strict_fields(document["components"]["schemas"], fields)
    return STRICT_TEMPLATE.format(
        schema_names=", ".join(json.dumps(name) for name in required),
        required="\n".join(
            f"    {json.dumps(schema)}: {tuple(members)!r},"
            for schema, members in required.items()
        ),
        enums="\n".join(enum_lines(enums)),
    )


def named_enums(schemas: Mapping[str, Any], declared: str) -> str:
    """The source of one documented `Literal` alias per enum in `NAMED_ENUMS`.

    Args:
        schemas: The served document's component schemas.
        declared: The generated module the aliases join, whose top-level names
            they must not take.
    """
    aliases = []
    for name, (path, doc) in NAMED_ENUMS.items():
        if f"\nclass {name}(" in declared or f"\ntype {name} =" in declared:
            raise SystemExit(f"the enum name {name} is declared in {relative(WIRE)}")
        node: Any = schemas
        for key in path:
            node = node.get(key) if isinstance(node, Mapping) else None
        values = node.get("enum") if isinstance(node, Mapping) else None
        if not values or not all(isinstance(value, str) for value in values):
            raise SystemExit(f"{'.'.join(path)} holds no string enum for {name}")
        field = ".".join(key for key in path if key != "properties")
        literal = ", ".join(json.dumps(value) for value in values)
        aliases.append(
            f"type {name} = Literal[{literal}]\n"
            f'"""{doc}\n\nThe values of `{field}` in the served document.\n"""\n'
        )
    return "\n\n".join(aliases)


def render_wire(schemas: Mapping[str, Any]) -> str:
    """The source of `_generated/wire.py`, before formatting."""
    with tempfile.TemporaryDirectory() as scratch:
        output = Path(scratch) / "wire.py"
        # Its warnings about `$id`-relative references repeat on every run, so its
        # output is shown only when it fails.
        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                f"--input={OPENAPI}",
                f"--output={output}",
                *CODEGEN_ARGS,
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            raise SystemExit(f"datamodel-code-generator failed:\n{result.stderr}")
        lines = output.read_text().splitlines(keepends=True)
    # datamodel-code-generator opens with a comment block naming its input. The
    # module docstring replaces it.
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    source = "".join(lines)
    return f"{WIRE_DOCSTRING}{source}\n\n{named_enums(schemas, source)}"


def render_reading_order(rule: Mapping[str, Any]) -> str:
    """The source of `_generated/reading_order.py`, before formatting."""
    where = relative(READING_ORDER_RULE)
    if rule.get("format_version") != 1 or rule.get("rule") != "reading-order":
        raise SystemExit(f"{where}: not format version 1 of the reading-order rule")
    slots = rule.get("reading_columns")
    if not isinstance(slots, list) or not slots:
        raise SystemExit(f"{where}: reading_columns holds no slot")
    seen: set[str] = set()
    for slot in slots:
        if (
            not isinstance(slot, list)
            or not slot
            or not all(isinstance(name, str) and name for name in slot)
        ):
            raise SystemExit(f"{where}: the slot {slot!r} is not a list of names")
        if seen.intersection(slot) or len(set(slot)) != len(slot):
            raise SystemExit(f"{where}: the slot {slot!r} lists a name twice")
        if "stat_var" in slot or "part" in slot:
            raise SystemExit(f"{where}: the slot {slot!r} names stat_var or part")
        seen.update(slot)
    return READING_ORDER_TEMPLATE.format(
        slots="\n".join(f"    {tuple(slot)!r}," for slot in slots)
    )


def render_role_keys(rule: Mapping[str, Any]) -> str:
    """The source of `_generated/role_keys.py`, before formatting."""
    where = relative(ROLE_KEYS_RULE)
    if rule.get("format_version") != 1 or rule.get("rule") != "role-keys":
        raise SystemExit(f"{where}: not format version 1 of the role-keys rule")
    keys = rule.get("keys")
    if (
        not isinstance(keys, dict)
        or not keys
        or not all(
            isinstance(name, str) and name for item in keys.items() for name in item
        )
    ):
        raise SystemExit(f"{where}: keys is not a map of caller keys to wire roles")
    wires = list(keys.values())
    if len(set(wires)) != len(wires):
        raise SystemExit(f"{where}: keys maps two caller keys to one wire role")
    if spelled := [wire for key, wire in keys.items() if wire != key and wire in keys]:
        raise SystemExit(f"{where}: the wire role {spelled[0]!r} is another key")
    flow_keys = rule.get("flow_keys")
    if (
        not isinstance(flow_keys, list)
        or not flow_keys
        or len(set(flow_keys)) != len(flow_keys)
        or not all(isinstance(key, str) and keys.get(key) == key for key in flow_keys)
    ):
        raise SystemExit(
            f"{where}: flow_keys is not a list of keys the rule maps to themselves"
        )
    return ROLE_KEYS_TEMPLATE.format(
        keys="\n".join(f"    {key!r}: {wire!r}," for key, wire in keys.items()),
        flow_keys=tuple(flow_keys),
    )


def render_file_selector(rule: Mapping[str, Any]) -> str:
    """The source of `_generated/file_selector.py`, before formatting."""
    where = relative(FILE_SELECTOR_RULE)
    if rule.get("format_version") != 1 or rule.get("rule") != "file-selector":
        raise SystemExit(f"{where}: not format version 1 of the file-selector rule")
    keys = rule.get("query_keys")
    if (
        not isinstance(keys, list)
        or not keys
        or len(set(keys)) != len(keys)
        or not all(isinstance(key, str) and key for key in keys)
    ):
        raise SystemExit(f"{where}: query_keys is not a list of distinct names")
    return FILE_SELECTOR_TEMPLATE.format(query_keys=tuple(keys))


def main(argv: list[str] | None = None) -> int:
    """Write or check the modules and return the exit status."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when a generated module differs instead of writing",
    )
    args = parser.parse_args(argv)

    sync_contract.require_current()
    document = json.loads(OPENAPI.read_text(encoding="utf-8"))
    fields = json.loads(STRICT_FIELDS.read_text(encoding="utf-8"))
    generated = {
        WIRE: render_wire(document["components"]["schemas"]),
        STRICT: render_strict(document, fields),
        READING_ORDER: render_reading_order(
            json.loads(READING_ORDER_RULE.read_text(encoding="utf-8"))
        ),
        ROLE_KEYS: render_role_keys(
            json.loads(ROLE_KEYS_RULE.read_text(encoding="utf-8"))
        ),
        FILE_SELECTOR: render_file_selector(
            json.loads(FILE_SELECTOR_RULE.read_text(encoding="utf-8"))
        ),
    }
    differs = [
        path
        for path, source in generated.items()
        if write_or_check(path, source, check=args.check)
    ]
    if args.check:
        for path in differs:
            print(
                f"{relative(path)} is stale; run scripts/gen_wire.py", file=sys.stderr
            )
        return 1 if differs else 0
    for path in differs:
        print(f"wrote {relative(path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
